# ------------------------------------------------------------------ settings
@dataclass
class Settings:
    lm: str = "models/lm"                  # bundle folders (scripts/export.py writes them)
    parser: str = "models/parser"
    device: str = "cpu"                    # M4: for one request at a time the CPU beats the Mac's GPU
    threads: int = 0                       # torch threads; 0 = PyTorch's default (one per core)
    max_queue_generate: int = 8            # waiting generation requests before 503
    max_queue_parse: int = 64              # waiting parse requests before 503
    max_batch: int = 16                    # parse requests per forward pass; 1 = no batching
    max_wait_ms: float = 0.0               # how long a parse batch waits for company
    ui: bool = True                        # mount the Gradio demo at /

    @classmethod
    def from_env(cls) -> "Settings":
        values = {}
        for f in fields(cls):
            raw = os.environ.get(f"TINYGPT_{f.name.upper()}")
            if raw is not None:
                kind = type(f.default)
                values[f.name] = raw.lower() in ("1", "true", "yes") if kind is bool else kind(raw)
        return cls(**values)


# ------------------------------------------------------------------ metrics
class Metrics:
    """Prometheus metrics in a registry of their own (tests build many apps in one process)."""

    def __init__(self):
        r = self.registry = CollectorRegistry()
        self.requests = Counter("tinygpt_requests", "HTTP requests", ["endpoint", "status"], registry=r)
        self.latency = Histogram("tinygpt_request_seconds", "Request start to last byte", ["endpoint"], registry=r,
                                 buckets=(.005, .01, .025, .05, .1, .25, .5, 1, 2.5, 5, 10, 30))
        self.queue_wait = Histogram("tinygpt_queue_seconds", "Time a job waited for its worker", ["worker"],
                                    registry=r, buckets=(.001, .005, .01, .05, .1, .5, 1, 5, 10, 30))
        self.rejected = Counter("tinygpt_rejected", "Requests refused with 503: queue full", ["worker"], registry=r)
        self.waiting = Gauge("tinygpt_waiting_jobs", "Jobs waiting for a worker", ["worker"], registry=r)
        self.batch = Histogram("tinygpt_parse_batch_size", "Requests per parser forward pass", registry=r,
                               buckets=(1, 2, 4, 8, 16, 32, 64))
        self.tokens = Counter("tinygpt_generated_tokens", "Tokens generated", registry=r)
        self.finish = Counter("tinygpt_generations", "Finished generations", ["reason"], registry=r)
        self.first_token = Histogram("tinygpt_first_token_seconds", "Prompt read + first token chosen", registry=r,
                                     buckets=(.005, .01, .025, .05, .1, .25, .5, 1, 2.5))

    def watch(self, *workers) -> None:
        for w in workers:
            self.waiting.labels(w.name).set_function(lambda w=w: w.waiting)

    def on_event(self, kind: str, data: dict) -> None:            # called from the worker threads
        if kind == "queue":
            self.queue_wait.labels(data["worker"]).observe(data["seconds"])
        elif kind == "rejected":
            self.rejected.labels(data["worker"]).inc()
        elif kind == "batch":
            self.batch.observe(data["size"])
        elif kind == "generated":
            self.tokens.inc(data["tokens"])
            self.finish.labels(data["reason"]).inc()
            if data["first_token_seconds"] is not None:
                self.first_token.observe(data["first_token_seconds"])


ENDPOINTS = {"/health", "/v1/info", "/v1/generate", "/v1/generate/stream", "/v1/parse", "/metrics"}
REQUEST_ID = re.compile(r"[\w.-]{1,64}")


class RequestMiddleware:
    """Pure ASGI middleware: request id, one log line and metrics per request. (Starlette's
    BaseHTTPMiddleware would time only until the headers — the start of a stream — and wraps
    streaming bodies in ways that have broken cancellation; plain ASGI sees the last byte.)"""

    def __init__(self, app, metrics: Metrics):
        self.app, self.metrics = app, metrics

    async def __call__(self, scope, receive, send):
        if scope["type"] != "http":
            return await self.app(scope, receive, send)
        start, status = time.perf_counter(), [500]
        given = dict(scope["headers"]).get(b"x-request-id", b"").decode("latin-1")
        rid = given if REQUEST_ID.fullmatch(given) else uuid.uuid4().hex[:16]

        async def send_with_id(message):
            if message["type"] == "http.response.start":
                status[0] = message["status"]
                message.setdefault("headers", [])
                message["headers"] = [*message["headers"], (b"x-request-id", rid.encode())]
            await send(message)

        try:
            await self.app(scope, receive, send_with_id)
        finally:
            seconds = time.perf_counter() - start
            endpoint = scope["path"] if scope["path"] in ENDPOINTS else "ui"
            self.metrics.requests.labels(endpoint, str(status[0])).inc()
            self.metrics.latency.labels(endpoint).observe(seconds)
            if endpoint != "ui":
                log.info("%s %s %d %.1f ms id=%s", scope["method"], scope["path"], status[0], seconds * 1000, rid)


# ------------------------------------------------------------------ request and response bodies
class GenerateRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", json_schema_extra={"examples": [
        {"prompt": "भारत की राजधानी", "max_new_tokens": 60, "temperature": 0.8, "top_k": 50}]})
    prompt: str = Field("", max_length=2000, description="The start of the text; empty = a new document")
    max_new_tokens: int = Field(120, ge=1, le=256)
    temperature: float = Field(0.8, ge=0.0, le=2.0, description="0 = greedy")
    top_k: int | None = Field(50, ge=0, le=8192, description="keep the k most likely tokens; 0 or null = off")
    top_p: float | None = Field(None, gt=0.0, le=1.0, description="nucleus sampling; null = off")
    min_p: float | None = Field(None, ge=0.0, lt=1.0, description="null or 0 = off")
    repetition_penalty: float = Field(1.0, ge=1.0, le=2.0, description="1 = off")
    seed: int | None = Field(None, ge=0, lt=2**31, description="the same seed and settings give the same text")

    def params(self) -> GenerateParams:
        return GenerateParams(self.max_new_tokens, self.temperature, self.top_k, self.top_p, self.min_p or None,
                              self.repetition_penalty, self.seed)


class GenerateResponse(BaseModel):
    text: str
    tokens: int
    finish_reason: Literal["stop", "length", "cancelled"]
    seed: int
    seconds: float = Field(description="generation time, from reading the prompt to the last token")
    first_token_seconds: float | None
    queue_seconds: float = Field(description="time spent waiting for the model")


class ParseRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", json_schema_extra={"examples": [
        {"text": "kal subah 7 baje ka alarm laga do"}]})
    text: str = Field(min_length=1, max_length=300)


class Slot(BaseModel):
    label: str
    text: str


class Span(BaseModel):
    text: str
    label: str | None


class ParseResponse(BaseModel):
    text: str = Field(description="the request, normalised")
    written: str = Field(description="what the model wrote: the request with brackets")
    parse: str = Field(description="the decoupled tree (intent + slots), what M5 scored")
    valid: bool
    intent: str | None
    slots: list[Slot]
    spans: list[Span]
    tokens: int
    batch_size: int = Field(description="requests that shared this forward pass")
    queue_seconds: float


# ------------------------------------------------------------------ the app
def submit(worker, job: Job) -> Job:
    try:
        return worker.submit(job)
    except Busy as e:
        raise HTTPException(503, str(e), headers={"Retry-After": "1"}) from e


async def generate_job(req: GenerateRequest, request: Request) -> Job:
    """A dependency of the streaming endpoint, so that a full queue is a 503 *before* the stream's
    200 has been sent. (Module level: FastAPI must be able to resolve it from its annotation.)"""
    return submit(request.app.state.lm, Job((req.prompt, req.params()), AsyncChannel()))


def peak_memory_mb() -> float:
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    return peak / 2**20 if sys.platform == "darwin" else peak / 2**10     # bytes on macOS, KiB on Linux


def create_app(settings: Settings | None = None, generator: TextGenerator | None = None,
               parser: Parser | None = None) -> FastAPI:
    """The app. Models load at startup (lifespan), not at import; tests pass small engines instead."""
    settings = settings or Settings.from_env()
    metrics = Metrics()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        t0 = time.perf_counter()
        if settings.threads:
            torch.set_num_threads(settings.threads)
        gen = generator or TextGenerator.from_bundle(settings.lm, settings.device)
        par = parser or Parser.from_bundle(settings.parser, settings.device)
        app.state.lm = GenerateWorker(gen, settings.max_queue_generate, on_event=metrics.on_event).start()
        app.state.parse = ParseWorker(par, settings.max_queue_parse, settings.max_batch, settings.max_wait_ms,
                                      on_event=metrics.on_event).start()
        metrics.watch(app.state.lm, app.state.parse)
        app.state.load_seconds = time.perf_counter() - t0
        log.info("models loaded in %.1f s on %s, %d torch threads", app.state.load_seconds, settings.device,
                 torch.get_num_threads())
        yield
        app.state.lm.stop()
        app.state.parse.stop()

    app = FastAPI(title="TinyGPT", version=__version__, lifespan=lifespan,
                  description="A small GPT for Hindi and Hinglish, built from scratch: text generation and "
                              "Hinglish request parsing. Source: https://github.com/TanushLukha/TinyGPT")
    app.add_middleware(RequestMiddleware, metrics=metrics)

    @app.get("/health")
    async def health() -> dict:
        return {"status": "ok"}

    @app.get("/v1/info")
    async def info(request: Request) -> dict:
        s = request.app.state
        return {"version": __version__, "torch": torch.__version__, "device": settings.device,
                "threads": torch.get_num_threads(), "load_seconds": round(s.load_seconds, 2),
                "peak_memory_mb": round(peak_memory_mb()),
                "models": {"generate": s.lm.generator.info, "parse": s.parse.parser.info},
                "limits": {"max_new_tokens": 256, "prompt_chars": 2000, "request_chars": 300,
                           "max_queue_generate": settings.max_queue_generate,
                           "max_queue_parse": settings.max_queue_parse, "max_batch": settings.max_batch}}

    @app.post("/v1/generate")
    async def generate(req: GenerateRequest, request: Request) -> GenerateResponse:
        job = submit(request.app.state.lm, Job((req.prompt, req.params()), AsyncChannel()))
        pieces = []
        try:
            while True:
                item = await job.channel.get()
                if isinstance(item, Piece):
                    pieces.append(item.text)
                elif isinstance(item, Done):
                    return GenerateResponse(text="".join(pieces), tokens=item.tokens,
                                            finish_reason=item.finish_reason, seed=item.seed,
                                            seconds=item.seconds, first_token_seconds=item.first_token_seconds,
                                            queue_seconds=job.queue_seconds)
                else:
                    raise HTTPException(500, item.message)
        finally:
            job.cancel.set()

    @app.post("/v1/generate/stream", response_class=EventSourceResponse)
    async def generate_stream(job: Annotated[Job, Depends(generate_job)]) -> AsyncIterable[ServerSentEvent]:
        """`token` events {"text": ...} while the text is generated, then one `done` event with the
        same fields as /v1/generate (without the text). Disconnecting stops the generation."""
        try:
            while True:
                item = await job.channel.get()
                if isinstance(item, Piece):
                    yield ServerSentEvent(data={"text": item.text}, event="token")
                elif isinstance(item, Done):
                    yield ServerSentEvent(event="done", data={
                        "tokens": item.tokens, "finish_reason": item.finish_reason, "seed": item.seed,
                        "seconds": item.seconds, "first_token_seconds": item.first_token_seconds,
                        "queue_seconds": job.queue_seconds})
                    return
                else:
                    yield ServerSentEvent(data={"error": item.message}, event="error")
                    return
        finally:
            job.cancel.set()                    # the client left (or the text is done): stop working

    @app.post("/v1/parse")
    async def parse(req: ParseRequest, request: Request) -> ParseResponse:
        worker = request.app.state.parse
        try:
            worker.parser.prompt(req.text)      # empty or too long: 422 now, not after queueing
        except ValueError as e:
            raise HTTPException(422, str(e)) from e
        job = submit(worker, Job(req.text, AsyncChannel()))
        item = await job.channel.get()
        if isinstance(item, Error):
            raise HTTPException(500, item.message)
        data = item.to_dict()
        data.pop("error")
        return ParseResponse(**data, queue_seconds=job.queue_seconds)

    @app.get("/metrics")
    async def prometheus() -> Response:
        return Response(generate_latest(metrics.registry), media_type=CONTENT_TYPE_LATEST)

    if settings.ui:
        mount_ui(app, settings, generator, parser)
    return app


def mount_ui(app: FastAPI, settings: Settings, generator=None, parser=None) -> None:
    """The Gradio demo at /, calling the models through the same workers as the API."""
    import gradio as gr

    from .ui import build_ui, theme

    def generate(prompt: str, params: GenerateParams):
        job = app.state.lm.submit(Job((prompt, params), SyncChannel()))
        try:
            while True:
                item = job.channel.get(timeout=300)
                if isinstance(item, Error):
                    raise RuntimeError(item.message)
                yield item
                if isinstance(item, Done):
                    return
        finally:
            job.cancel.set()

    def parse(texts: list[str]) -> list[ParseResult]:
        jobs = [app.state.parse.submit(Job(t, SyncChannel())) for t in texts]
        results = []
        for job in jobs:
            item = job.channel.get(timeout=120)
            if isinstance(item, Error):
                raise RuntimeError(item.message)
            results.append(item)
        return results

    lm_config = generator.config if generator else read_config(settings.lm)
    parser_config = parser.config if parser else read_config(settings.parser)
    gr.mount_gradio_app(app, build_ui(generate, parse, lm_config, parser_config), path="/", theme=theme(),
                        footer_links=["api", "gradio"])
