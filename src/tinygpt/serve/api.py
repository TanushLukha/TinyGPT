"""The HTTP service (M6): FastAPI in front of the two worker threads.

    GET  /health                liveness: the process is up and both models are loaded
    GET  /v1/info               the models, their scores, the limits, memory
    POST /v1/generate           prompt -> text, as JSON once the text is complete
    POST /v1/generate/stream    prompt -> text, as Server-Sent Events while it is generated
    POST /v1/parse              Hinglish request -> intent and slots
    GET  /metrics               Prometheus metrics: requests, latency, queues, batch sizes, tokens
    GET  /docs                  interactive API documentation, generated by FastAPI from the code
    GET  /                      the Gradio demo (TINYGPT_UI=0 turns it off)

    python -m tinygpt.serve                                    # or:
    uvicorn tinygpt.serve.api:create_app --factory --port 8000

Settings come from environment variables (TINYGPT_*, see Settings), so the same image runs
anywhere with different settings and no code change.
"""
